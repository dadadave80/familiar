pub const GOODS: [&str; 2] = ["glass", "reed"];
pub const GLASS: usize = 0;
pub const REED: usize = 1;
/// Cargo that reaches the dock becomes goods through this one table. Unlisted cargo
/// (`moth`, `vane`) mints nothing. David may change it before deploy.
pub const CARGO_GOODS: [(&str, Option<usize>); 5] = [
    ("lens", Some(GLASS)),
    ("moth", None),
    ("chart", Some(REED)),
    ("salvage", Some(REED)),
    ("vane", None),
];
pub const BASE: [u128; 2] = [8, 4];
pub const TARGET: [u128; 2] = [40, 40];
pub const START_STOCK: [u64; 2] = [40, 40];
pub const TILL_START: u64 = 300;
pub const TILL_CAP: u64 = 300;
pub const TILL_REFILL: u64 = 60;
pub const DAY_NS: u64 = 86_400_000_000_000;
pub const DAILY_UNITS: u32 = 20;
pub const TRADE_QTY_MAX: u32 = 20;
pub const PURSE_MAX: u64 = 24;
pub const WISH_QTY_MAX: u8 = 2;
pub const FILLS_PER_TX: usize = 3;
/// Bounds the per-trade scan of waiting wishes for one good.
pub const WISH_QUEUE_CAP: usize = 32;
pub const PET_ID_MAX: usize = 64;
pub const COMMAND_LEN_MAX: usize = 24;
pub const COURT_AREA: &str = "beacon";
/// Even days replay `first_light_v1`, odd days `first_light_v2`, always a fresh beacon outing.
pub const COURTS: [&str; 2] = [storycraft::CONTENT_VERSION, court::CONTENT_VERSION];
pub const TOOLS: [&str; 2] = ["rope", "lantern"];
/// Best (glass, reed) haul per court and tool, generated by `bun scripts/season-best-haul.ts`
/// into `fixtures/best-haul.json` and checked by tests on both sides.
pub const BEST_HAUL: [[(u64, u64); 2]; 2] = [[(1, 1), (1, 2)], [(1, 0), (1, 0)]];
/// Storage charged once per account record, and once per pet record (wish, queue slot, postcard).
pub const ACCOUNT_BYTES: u64 = 400;
pub const PET_BYTES: u64 = 850;

fn day_of(timestamp: u64) -> u64 {
    timestamp / DAY_NS
}
fn today() -> u64 {
    day_of(env::block_timestamp())
}
pub fn court_of(day: u64) -> usize {
    (day % 2) as usize
}
fn good_index(good: &str) -> Option<usize> {
    GOODS.iter().position(|g| *g == good)
}
fn to_u64(v: u128) -> u64 {
    u64::try_from(v).unwrap_or(u64::MAX)
}
fn bytes_cost(bytes: u64) -> u128 {
    env::storage_byte_cost().as_yoctonear() * u128::from(bytes)
}
pub fn min_storage_deposit() -> NearToken {
    NearToken::from_yoctonear(bytes_cost(ACCOUNT_BYTES + PET_BYTES))
}
fn emit(event: &str, data: Value) {
    env::log_str(&format!(
        "EVENT_JSON:{}",
        json!({"standard":"familiar_season","version":"1.0.0","event":event,"data":[data]})
    ));
}
/// Maps docked cargo to goods through CARGO_GOODS.
pub fn cargo_goods(cargo: &[String]) -> [u64; 2] {
    let mut out = [0u64; 2];
    for item in cargo {
        if let Some((_, Some(g))) = CARGO_GOODS.iter().find(|(name, _)| name == item) {
            out[*g] += 1;
        }
    }
    out
}

