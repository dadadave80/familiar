    // ---------- storage ----------

    /// One-time registration for the predecessor (at least `min_storage_deposit`), or a top-up.
    #[payable]
    pub fn storage_deposit(&mut self) -> StorageBalance {
        let who = env::predecessor_account_id();
        let deposit = env::attached_deposit();
        let account = match self.accounts.get_mut(&who) {
            Some(a) => {
                a.storage_deposit = a.storage_deposit.saturating_add(deposit);
                a.clone()
            }
            None => {
                require!(deposit >= min_storage_deposit(), "ERR_STORAGE_DEPOSIT");
                let a = Account {
                    shells: 0,
                    goods: [0, 0],
                    trade_day: 0,
                    traded: [0, 0],
                    last_mint: None,
                    storage_deposit: deposit,
                    storage_bytes: ACCOUNT_BYTES,
                };
                self.accounts.insert(who, a.clone());
                a
            }
        };
        Self::balance(&account)
    }

    pub fn storage_balance_of(&self, account_id: AccountId) -> Option<StorageBalance> {
        self.accounts.get(&account_id).map(Self::balance)
    }

    pub fn storage_minimum(&self) -> NearToken {
        min_storage_deposit()
    }

    /// Withdraw deposit not covering charged storage. Charged bytes are never refunded:
    /// account and pet records persist. Requires exactly one yoctoNEAR (full-access key).
    #[payable]
    pub fn storage_withdraw(&mut self) -> Promise {
        require!(
            env::attached_deposit() == NearToken::from_yoctonear(1),
            "ERR_ONE_YOCTO"
        );
        let who = env::predecessor_account_id();
        let account = self
            .accounts
            .get_mut(&who)
            .unwrap_or_else(|| env::panic_str("ERR_NOT_REGISTERED"));
        let amount = account.storage_available();
        require!(amount > 0, "ERR_NOTHING_TO_WITHDRAW");
        account.storage_deposit =
            NearToken::from_yoctonear(account.storage_deposit.as_yoctonear() - amount);
        Promise::new(who.clone())
            .transfer(NearToken::from_yoctonear(amount + 1))
            .then(
                Self::ext(env::current_account_id())
                    .with_static_gas(Gas::from_tgas(5))
                    .on_storage_withdraw(who, U128(amount)),
            )
    }

    /// Restores the deposit if the refund transfer failed. Never panics.
    #[private]
    pub fn on_storage_withdraw(&mut self, account_id: AccountId, amount: U128) -> bool {
        if familiar_common::promise_succeeded() {
            return true;
        }
        if let Some(a) = self.accounts.get_mut(&account_id) {
            a.storage_deposit = a
                .storage_deposit
                .saturating_add(NearToken::from_yoctonear(amount.0));
        }
        false
    }

    // ---------- daily court ----------

    /// Replays today's court and mints the cargo that docked, once per account per day.
    pub fn claim_daily(
        &mut self,
        rules_version: String,
        content_version: String,
        tool: String,
        area: String,
        commands: Vec<String>,
    ) -> Mint {
        let who = env::predecessor_account_id();
        let day = today();
        let court_index = court_of(day);
        require!(
            rules_version == storycraft::RULES_VERSION,
            "ERR_RULES_VERSION"
        );
        require!(content_version == COURTS[court_index], "ERR_WRONG_COURT");
        let limit = if court_index == 0 { 15 } else { 24 };
        require!(
            commands.len() <= limit && commands.iter().all(|s| s.len() <= COMMAND_LEN_MAX),
            "ERR_COMMAND_BOUND"
        );
        let tool_index = TOOLS
            .iter()
            .position(|t| *t == tool)
            .unwrap_or_else(|| env::panic_str("ERR_REPLAY_CONTEXT"));
        require!(area == COURT_AREA, "ERR_REPLAY_CONTEXT");
        let account = self
            .accounts
            .get(&who)
            .unwrap_or_else(|| env::panic_str("ERR_NOT_REGISTERED"));
        require!(
            account.last_mint.as_ref().is_none_or(|m| m.day != day),
            "ERR_ALREADY_MINTED"
        );
        let (cargo, outcome) = if court_index == 0 {
            let run = historical_returns::replay(&tool, &[], &commands, &area)
                .unwrap_or_else(|_| env::panic_str("ERR_REPLAY"));
            (run.cargo, run.outcome)
        } else {
            let run = court::replay(&tool, &[], &commands, &area)
                .unwrap_or_else(|_| env::panic_str("ERR_REPLAY"));
            (run.cargo, run.outcome)
        };
        require!(outcome == "returned", "ERR_RETURN_REQUIRED");
        let goods = cargo_goods(&cargo);
        require!(goods[0] + goods[1] > 0, "ERR_NO_GOODS");
        let best = BEST_HAUL[court_index][tool_index];
        require!(goods[0] <= best.0 && goods[1] <= best.1, "ERR_HAUL_BOUND");
        self.settle(day);
        let prices = [0, 1].map(|g| shelf_price_fp(&self.shelf[g], g));
        let value = |h: (u64, u64)| u128::from(h.0) * prices[0] + u128::from(h.1) * prices[1];
        let value_fp = value((goods[0], goods[1]));
        let best_fp = BEST_HAUL[court_index]
            .iter()
            .map(|h| value(*h))
            .max()
            .unwrap_or(1)
            .max(1);
        let mint = Mint {
            day,
            content_version,
            tool,
            goods,
            value_fp: to_u64(value_fp),
            best_fp: to_u64(best_fp),
            score_bp: u32::try_from(value_fp * 10_000 / best_fp).unwrap_or(10_000),
        };
        let account = self.accounts.get_mut(&who).expect("registered");
        for (g, units) in goods.iter().enumerate() {
            account.goods[g] += units;
            self.goods_minted[g] += units;
        }
        account.last_mint = Some(mint.clone());
        emit(
            "mint",
            json!({"account_id": who, "day": day, "content_version": mint.content_version, "tool": mint.tool,
                   "commands": commands, "cargo": cargo, "glass": goods[0], "reed": goods[1],
                   "value_fp": mint.value_fp, "best_fp": mint.best_fp, "score_bp": mint.score_bp}),
        );
        mint
    }

    // ---------- Bram ----------

    /// Buy `qty` units; refuses if any unit costs more than `max_price` Shells.
    pub fn buy(&mut self, good: String, qty: u32, max_price: u64) -> Trade {
        self.trade(good, qty, max_price, true)
    }

    /// Sell `qty` units; refuses if any unit pays less than `min_price` Shells.
