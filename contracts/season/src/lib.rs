impl Season {
    fn balance(a: &Account) -> StorageBalance {
        StorageBalance {
            total: U128(a.storage_deposit.as_yoctonear()),
            available: U128(a.storage_available()),
        }
    }

    /// Lazy day effects: heat halving and till refill. Returns the shelf, till and Shells added.
    fn settled(&self, day: u64) -> ([Shelf; 2], u64, u64) {
        let shelf = self.shelf.map(|s| {
            if s.heat_day < day {
                Shelf {
                    stock: s.stock,
                    heat_fp: to_u64(decay_heat(u128::from(s.heat_fp), day - s.heat_day)),
                    heat_day: day,
                }
            } else {
                s
            }
        });
        let mut till = self.till;
        if self.till_day < day && till < TILL_CAP {
            till = till
                .saturating_add(TILL_REFILL.saturating_mul(day - self.till_day))
                .min(TILL_CAP);
        }
        (shelf, till, till - self.till.min(till))
    }
    fn settle(&mut self, day: u64) {
        let (shelf, till, added) = self.settled(day);
        self.shelf = shelf;
        self.till = till;
        self.till_day = self.till_day.max(day);
        self.shells_minted = self.shells_minted.saturating_add(added);
    }

    fn trade(&mut self, good: String, qty: u32, bound: u64, buying: bool) -> Trade {
        let who = env::predecessor_account_id();
        let g = good_index(&good).unwrap_or_else(|| env::panic_str("ERR_GOOD"));
        require!((1..=TRADE_QTY_MAX).contains(&qty), "ERR_TRADE_QTY");
        let day = today();
        let mut account = self
            .accounts
            .get(&who)
            .cloned()
            .unwrap_or_else(|| env::panic_str("ERR_NOT_REGISTERED"));
        if account.trade_day != day {
            account.trade_day = day;
            account.traded = [0, 0];
        }
        require!(account.traded[g] + qty <= DAILY_UNITS, "ERR_DAILY_LIMIT");
        self.settle(day);
        let (after, prices) = if buying {
            quote_buy(&self.shelf[g], g, u64::from(qty)).unwrap_or_else(|e| env::panic_str(e))
        } else {
            quote_sell(&self.shelf[g], g, u64::from(qty))
        };
        let total: u64 = prices.iter().sum();
        if buying {
            require!(prices.iter().all(|p| *p <= bound), "ERR_MAX_PRICE");
            require!(account.shells >= total, "ERR_SHELLS");
            account.shells -= total;
            account.goods[g] += u64::from(qty);
            self.till += total;
        } else {
            require!(prices.iter().all(|p| *p >= bound), "ERR_MIN_PRICE");
            require!(account.goods[g] >= u64::from(qty), "ERR_GOODS");
            require!(self.till >= total, "ERR_TILL_EMPTY");
            account.goods[g] -= u64::from(qty);
            account.shells += total;
            self.till -= total;
        }
        account.traded[g] += qty;
        self.shelf[g] = after;
        self.accounts.insert(who.clone(), account);
        self.trade_seq += 1;
        let side = if buying { "buy" } else { "sell" };
        emit(
            "trade",
            json!({"seq": self.trade_seq, "account_id": who, "side": side, "good": good,
                   "qty": qty, "unit_prices": prices, "total": total, "till": self.till,
                   "stock": self.shelf[g].stock}),
        );
        let trigger = Trigger {
            trade: self.trade_seq,
            account: who,
            side: side.into(),
            good: good.clone(),
        };
        let fills = self.fill_wishes(g, &trigger);
        Trade {
            seq: self.trade_seq,
            side: side.into(),
            good,
            qty,
            unit_prices: prices,
            total,
            fills,
        }
    }

    /// Fills waiting wishes for good `g` in arrival order, at most FILLS_PER_TX. Never panics.
    fn fill_wishes(&mut self, g: usize, trigger: &Trigger) -> Vec<Postcard> {
        let mut fills = vec![];
        let mut i = 0;
        while i < self.queues[g].len() && fills.len() < FILLS_PER_TX {
            let pet = self.queues[g][i].clone();
            match self.try_fill(&pet, Some(trigger)) {
                Some(card) => {
                    self.queues[g].remove(i);
                    fills.push(card);
                }
                None => i += 1,
            }
        }
        fills
    }

    /// Fills one wish if every unit is at or below its limit. Never panics.
    fn try_fill(&mut self, pet: &str, trigger: Option<&Trigger>) -> Option<Postcard> {
        let wish = self.wishes.get(pet)?.clone();
        let g = good_index(&wish.good)?;
        let (after, prices) = quote_buy(&self.shelf[g], g, u64::from(wish.qty)).ok()?;
        let paid: u64 = prices.iter().sum();
        if prices.iter().any(|p| *p > wish.limit) || paid > wish.purse {
            return None;
        }
        let refunded = wish.purse - paid;
        let owner = self.accounts.get_mut(&wish.owner)?;
        owner.goods[g] += u64::from(wish.qty);
        owner.shells += refunded;
        self.shelf[g] = after;
        self.till += paid;
        self.wishes.remove(pet);
        let card = Postcard {
            pet: wish.pet.clone(),
            owner: wish.owner.clone(),
            good: wish.good.clone(),
            qty: wish.qty,
            limit: wish.limit,
            outcome: "filled".into(),
            reason: if trigger.is_some() {
                "FILLED_BY_TRADE"
            } else {
                "FILLED_ON_SET"
            }
            .into(),
            unit_prices: prices,
            paid,
            refunded,
            trigger: trigger.cloned(),
            day: today(),
        };
        self.postcards.insert(pet.to_owned(), card.clone());
        emit("wish_fill", json!(card));
        Some(card)
    }

    /// Removes a waiting wish, refunds its purse to its owner and records the postcard.
    fn close_wish(&mut self, wish: &Wish, outcome: &str, reason: &str) -> Postcard {
        if let Some(g) = good_index(&wish.good) {
            self.queues[g].retain(|p| *p != wish.pet);
        }
        self.wishes.remove(&wish.pet);
        if let Some(a) = self.accounts.get_mut(&wish.owner) {
            a.shells += wish.purse;
        }
        let card = Postcard {
            pet: wish.pet.clone(),
            owner: wish.owner.clone(),
            good: wish.good.clone(),
            qty: wish.qty,
            limit: wish.limit,
            outcome: outcome.into(),
            reason: reason.into(),
            unit_prices: vec![],
            paid: 0,
            refunded: wish.purse,
            trigger: None,
            day: today(),
        };
        self.postcards.insert(wish.pet.clone(), card.clone());
        card
    }

    /// Owner from Root's `nft_token` result, read defensively.
    fn token_owner() -> Result<AccountId, &'static str> {
        if env::promise_results_count() != 1 {
            return Err("ERR_OWNER_LOOKUP");
        }
        let bytes = env::promise_result_checked(0, 16_384).map_err(|_| "ERR_OWNER_LOOKUP")?;
        let value: Value = serde_json::from_slice(&bytes).map_err(|_| "ERR_OWNER_LOOKUP")?;
        value
            .get("owner_id")
            .and_then(Value::as_str)
            .and_then(|s| s.parse().ok())
            .ok_or("ERR_NOT_OWNER")
    }

    /// All checks run before any write, so a refusal leaves state untouched.
    fn place_wish(
        &mut self,
        owner: AccountId,
        pet: String,
        good: String,
        limit: u64,
        qty: u8,
    ) -> Result<WishResult, &'static str> {
        let g = good_index(&good).ok_or("ERR_GOOD")?;
        if pet.is_empty() || pet.len() > PET_ID_MAX {
            return Err("ERR_PET_ID");
        }
        if !(1..=WISH_QTY_MAX).contains(&qty) || limit == 0 {
            return Err("ERR_WISH_QTY");
        }
        let purse = limit.saturating_mul(u64::from(qty));
        if purse > PURSE_MAX {
            return Err("ERR_PURSE_LIMIT");
        }
        let account = self.accounts.get(&owner).ok_or("ERR_NOT_REGISTERED")?;
        let existing = self.wishes.get(&pet).cloned();
        let refund_to_self = existing
            .as_ref()
            .filter(|w| w.owner == owner)
            .map_or(0, |w| w.purse);
        if account.shells.saturating_add(refund_to_self) < purse {
            return Err("ERR_SHELLS");
        }
        let new_record = existing.is_none() && !self.postcards.contains_key(&pet);
        if new_record && account.storage_available() < bytes_cost(PET_BYTES) {
            return Err("ERR_STORAGE");
        }
        let queued = self.queues[g].len().saturating_sub(usize::from(
            existing.as_ref().is_some_and(|w| w.good == good),
        ));
        if queued >= WISH_QUEUE_CAP {
            return Err("ERR_WISH_QUEUE_FULL");
        }
        // Commit.
        if let Some(old) = existing {
            let card = self.close_wish(&old, "replaced", "REPLACED_BY_OWNER");
            emit("wish_cancel", json!(card));
        }
        let day = today();
        self.settle(day);
        let account = self.accounts.get_mut(&owner).ok_or("ERR_NOT_REGISTERED")?;
        if new_record {
            account.storage_bytes += PET_BYTES;
        }
        account.shells -= purse;
        self.wish_seq += 1;
        let wish = Wish {
            pet: pet.clone(),
            owner,
            good,
            limit,
            qty,
            purse,
            seq: self.wish_seq,
            day,
        };
        self.wishes.insert(pet.clone(), wish.clone());
        emit("wish_set", json!(wish));
        if let Some(card) = self.try_fill(&pet, None) {
            return Ok(WishResult {
                status: "filled".into(),
                reason: card.reason.clone(),
                wish: None,
                postcard: Some(card),
            });
        }
        self.queues[g].push(pet);
        Ok(WishResult {
            status: "waiting".into(),
            reason: "WAITING".into(),
            wish: Some(wish),
            postcard: None,
        })
    }
}
