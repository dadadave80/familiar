/// Pure shelf simulation shared by trades, wish fills and views.
fn quote_buy(shelf: &Shelf, g: usize, qty: u64) -> Result<(Shelf, Vec<u64>), &'static str> {
    let mut s = *shelf;
    let mut prices = Vec::with_capacity(qty as usize);
    for _ in 0..qty {
        if s.stock == 0 {
            return Err("ERR_SHELF_EMPTY");
        }
        let p = price_fp(
            BASE[g],
            TARGET[g],
            u128::from(s.stock),
            u128::from(s.heat_fp),
        );
        prices.push(to_u64(buy_shells(p)));
        s.stock -= 1;
        s.heat_fp = s.heat_fp.saturating_add(S as u64);
    }
    Ok((s, prices))
}
fn quote_sell(shelf: &Shelf, g: usize, qty: u64) -> (Shelf, Vec<u64>) {
    let mut s = *shelf;
    let mut prices = Vec::with_capacity(qty as usize);
    for _ in 0..qty {
        // Bram pays at the post-unit stock: rounding and order favour the till.
        s.stock = s.stock.saturating_add(1);
        let p = price_fp(
            BASE[g],
            TARGET[g],
            u128::from(s.stock),
            u128::from(s.heat_fp),
        );
        prices.push(to_u64(sell_shells(p)));
    }
    (s, prices)
}
fn shelf_price_fp(s: &Shelf, g: usize) -> u128 {
    price_fp(
        BASE[g],
        TARGET[g],
        u128::from(s.stock),
        u128::from(s.heat_fp),
    )
}

